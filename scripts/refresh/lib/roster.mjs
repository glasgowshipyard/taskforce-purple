// Who is in Congress (#53): the site's member list kept in step with the
// public roster the identity crosswalk is built from (unitedstates/
// congress-legislators). New members are added (a record and a list entry,
// graded on the campaign that won their seat), members who left are taken
// off the list, and a member whose seat or party changed is updated. Pure:
// roster.mjs does the fetching and the writing.

import { STATES } from '../../../src/lib/states.js';

export const LEGISLATORS_URL =
  'https://unitedstates.github.io/congress-legislators/legislators-current.json';

// A truncated download or a schema change upstream must never empty the
// site's list: the same floor the crosswalk builder uses
export const MIN_LEGISLATORS = 530;
// More than this many arrivals or departures at once is either a new
// Congress (about 60 on 3 January) or a broken download; above it, nothing
// is written without --allow-big
export const MAX_CHANGES = 120;

const STATE_NAME = Object.fromEntries(STATES.map(s => [s.code, s.name]));
const PARTY = { Democrat: 'Democratic', Republican: 'Republican', Independent: 'Independent' };

/** A legislator's name as the site's list writes it: "Last, First M." */
function listName(n) {
  const middle = n.middle ? ` ${n.middle[0]}.` : '';
  const suffix = n.suffix ? ` ${n.suffix}` : '';
  return `${n.last}, ${n.first}${middle}${suffix}`;
}

/** The roster as the site's records see it: bioguide ID -> seat and party */
export function rosterFrom(legislators) {
  const out = new Map();
  for (const l of legislators || []) {
    const id = l.id?.bioguide;
    const term = l.terms?.[l.terms.length - 1];
    if (!id || !term) {
      continue;
    }
    const senate = term.type === 'sen';
    out.set(id, {
      bioguideId: id,
      name: listName(l.name || {}),
      party: PARTY[term.party] || term.party || null,
      state: STATE_NAME[term.state] || term.state,
      district: senate ? null : Number.isFinite(term.district) ? term.district : 0,
      chamber: senate ? 'Senate' : 'House',
      fecIds: [...new Set(l.id?.fec || [])].sort(),
    });
  }
  return out;
}

const SEAT_FIELDS = ['party', 'state', 'district', 'chamber'];
// Some stored districts are text ("11"): compare them as numbers
const seatValue = (field, v) =>
  field === 'district' && v !== null && v !== undefined && v !== '' ? Number(v) : (v ?? null);

/**
 * What changed between the roster and the site's list: { added: [roster
 * entries], removed: [list entries], changed: [{ id, name, fields: { field:
 * [was, now] } }] }. Names aren't compared: the two sources write them
 * differently.
 */
export function rosterChanges(roster, listMembers) {
  const onList = new Map((listMembers || []).map(m => [m.bioguideId, m]));
  const added = [...roster.values()].filter(r => !onList.has(r.bioguideId));
  const removed = [...onList.values()].filter(m => !roster.has(m.bioguideId));
  const changed = [];
  for (const [id, m] of onList) {
    const r = roster.get(id);
    if (!r) {
      continue;
    }
    const fields = {};
    for (const f of SEAT_FIELDS) {
      if (seatValue(f, m[f]) !== seatValue(f, r[f])) {
        fields[f] = [m[f] ?? null, r[f] ?? null];
      }
    }
    if (Object.keys(fields).length) {
      changed.push({ id, name: m.name, fields });
    }
  }
  return { added, removed, changed };
}

/** Why a roster mustn't be applied, or null when it's safe */
export function rosterRefusal(roster, changes, { allowBig = false } = {}) {
  if (roster.size < MIN_LEGISLATORS) {
    return `the roster has only ${roster.size} legislators (at least ${MIN_LEGISLATORS} expected): a broken download?`;
  }
  const big = Math.max(changes.added.length, changes.removed.length);
  if (big > MAX_CHANGES && !allowBig) {
    return `${changes.added.length} arrivals and ${changes.removed.length} departures at once: run with --allow-big if this is a new Congress`;
  }
  return null;
}

/** A new member's first record: their seat, and no grade until graded */
export function newRecord(r, now) {
  return {
    bioguideId: r.bioguideId,
    name: r.name,
    party: r.party,
    state: r.state,
    district: r.district,
    chamber: r.chamber,
    tier: 'N/A',
    totalRaised: 0,
    lastUpdated: now,
    addedFromRoster: now.slice(0, 10),
  };
}

/** workers/fec-crosswalk.js for a roster (scripts/build-fec-crosswalk.mjs) */
export function crosswalkFile(roster, { source = LEGISLATORS_URL, generated } = {}) {
  const sorted = Object.fromEntries(
    [...roster.values()].map(r => [r.bioguideId, r.fecIds]).sort(([a], [b]) => a.localeCompare(b))
  );
  const withFec = Object.values(sorted).filter(ids => ids.length).length;
  return `// GENERATED by scripts/build-fec-crosswalk.mjs - do not edit by hand.
// Source: ${source}
// Generated: ${generated}
// ${roster.size} legislators, ${withFec} with at least one FEC candidate ID.
//
// bioguide ID -> FEC candidate IDs. A member can hold several: one per office
// they have run for (e.g. a House member now running for Senate).

export const FEC_CROSSWALK = ${JSON.stringify(sorted, null, 2)};
`;
}

/** The crosswalk's mapping, ignoring its header (the generated date) */
export const crosswalkBody = text => String(text).slice(String(text).indexOf('export const'));
