#!/usr/bin/env node
/**
 * Regenerate workers/fec-crosswalk.js: bioguide ID -> FEC candidate IDs for
 * every sitting member of Congress.
 *
 * Source: unitedstates/congress-legislators, a maintained public dataset that
 * records each legislator's FEC candidate IDs directly. We previously found
 * members by searching FEC for their surname, and on 2026-09-26 that had tied
 * 35 members to the wrong person (issue #41). An ID lookup cannot make that
 * mistake; a name search always can.
 *
 * The source file is ~1.4 MB. We extract the ~20 KB we need here, at build
 * time, rather than fetching and parsing it inside the Worker, where it would
 * cost a subrequest per run and risk the free plan's 10 ms CPU limit.
 *
 * Run when membership changes (special elections, resignations, new Congress):
 *   node scripts/build-fec-crosswalk.mjs
 * then commit and deploy the data-pipeline worker.
 */

import { writeFileSync } from 'node:fs';

const SOURCE = 'https://unitedstates.github.io/congress-legislators/legislators-current.json';
const OUT = new URL('../workers/fec-crosswalk.js', import.meta.url);

const res = await fetch(SOURCE);
if (!res.ok) {
  console.error(`Fetch failed: HTTP ${res.status}`);
  process.exit(1);
}
const legislators = await res.json();

const members = {};
let withFec = 0;
for (const l of legislators) {
  const bioguide = l.id?.bioguide;
  if (!bioguide) {
    continue;
  }
  const fec = [...new Set(l.id?.fec || [])].sort();
  members[bioguide] = fec;
  if (fec.length > 0) {
    withFec++;
  }
}

// Refuse to write something obviously broken: a truncated download or a
// schema change upstream would otherwise silently un-map most of Congress.
const count = Object.keys(members).length;
if (count < 530 || withFec < 520) {
  console.error(`Refusing to write: only ${count} legislators, ${withFec} with FEC IDs`);
  process.exit(1);
}

const sorted = Object.fromEntries(Object.entries(members).sort(([a], [b]) => a.localeCompare(b)));

const body = `// GENERATED by scripts/build-fec-crosswalk.mjs - do not edit by hand.
// Source: ${SOURCE}
// Generated: ${new Date().toISOString()}
// ${count} legislators, ${withFec} with at least one FEC candidate ID.
//
// bioguide ID -> FEC candidate IDs. A member can hold several: one per office
// they have run for (e.g. a House member now running for Senate).

export const FEC_CROSSWALK = ${JSON.stringify(sorted, null, 2)};
`;

writeFileSync(OUT, body);
console.log(`Wrote ${OUT.pathname}: ${count} legislators, ${withFec} with FEC IDs`);
