/**
 * FEC IDENTITY - which FEC candidate records belong to which member.
 *
 * Until 2026-09-26 members were found by searching FEC for their surname and
 * the first plausible hit was cached forever. That tied 35 members to the
 * wrong person (issue #41): a sitting House member to a sitting senator, a son
 * to his father's Senate committee, a senator to her father. Name search
 * cannot be made safe - common surnames collide, and FEC's incumbent flag
 * describes each candidate's LAST race, not whether they hold office now.
 *
 * Identity now comes from the congress-legislators crosswalk (bioguide ID ->
 * FEC candidate IDs), regenerated by scripts/build-fec-crosswalk.mjs. No
 * inference: an ID is either on the member's list or it is not theirs.
 */

import { FEC_CROSSWALK } from './fec-crosswalk.js';

/** FEC candidate IDs recorded for this member. Empty = none known (non-filer). */
export function crosswalkIdsFor(bioguideId, crosswalk = FEC_CROSSWALK) {
  return crosswalk[bioguideId] || [];
}

/**
 * Is `candidateId` one of this member's recorded FEC identities?
 * Anything not on the list is treated as someone else's, however similar the
 * name - that is the whole point.
 */
export function isVerifiedIdentity(bioguideId, candidateId, crosswalk = FEC_CROSSWALK) {
  if (!candidateId) {
    return false;
  }
  return crosswalkIdsFor(bioguideId, crosswalk).includes(candidateId);
}

/**
 * The FEC office code ('H' or 'S') for the seat the member holds now.
 */
export function heldOffice(member) {
  const chamber = (member.chamber || '').toLowerCase();
  if (chamber.startsWith('house')) {
    return 'H';
  }
  if (chamber.startsWith('senate')) {
    return 'S';
  }
  return member.district ? 'H' : 'S';
}

/**
 * Choose the candidate record for the office the member currently holds.
 *
 * `candidates` are FEC /candidates/search/ records, already restricted to the
 * member's crosswalk IDs. Among those for the held office, the most recently
 * active wins (a member can hold two IDs for the same office, e.g. an old
 * run and a current one). If none matches the held office, fall back to the
 * most recently active overall rather than returning nothing - the identity
 * is still verified, only the office is unusual.
 */
export function selectPrimaryCandidate(candidates, office) {
  if (!candidates || candidates.length === 0) {
    return null;
  }
  const byRecency = [...candidates].sort(
    (a, b) => (b.active_through || 0) - (a.active_through || 0)
  );
  return byRecency.find(c => c.office === office) || byRecency[0];
}

/**
 * Candidate records with a principal committee filing in `cycle` - i.e. every
 * campaign the person is running right now. For a House member running for
 * Senate this returns both.
 */
export function activeCandidates(candidates, cycle) {
  return (candidates || []).filter(c =>
    (c.principal_committees || []).some(
      pc => (pc.designation === 'P' || pc.designation === 'A') && (pc.cycles || []).includes(cycle)
    )
  );
}
